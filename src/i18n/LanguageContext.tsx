export function localizeAuditText(text: string, language: AppLanguage): string {
  if (!text || language === 'en') return text;
  if (vi[text]) return vi[text];

  const prefixes: Array<[string, string]> = [
    ['Submission ID:', 'ID bản gửi:'],
    ['Vote ID:', 'ID phiếu:'],
    ['File:', 'Tệp:'],
    ['Chapter ID:', 'ID chapter:'],
    ['Session ID:', 'ID phiên:'],
    ['Directive ID:', 'ID chỉ thị:'],
    ['Page ID:', 'ID trang:'],
    ['Annotation ID:', 'ID chú thích:'],
    ['Series ID:', 'ID series:'],
    ['Rating ID:', 'ID đánh giá:'],
    ['Task:', 'Task:'],
    ['Title:', 'Tiêu đề:'],
    ['Series:', 'Series:'],
    ['Proposal:', 'Đề xuất:'],
  ];

  for (const [source, translated] of prefixes) {
    if (text.startsWith(source)) return translated + text.slice(source.length);
  }

  return text.replace(/\bUntitled\b/g, 'Chưa đặt tên');
}

